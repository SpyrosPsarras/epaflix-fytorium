import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { logIn } from './helpers/login';
import { addPlantForSite } from './helpers/plants';

test('moves to graveyard, restores, corrects species and permanently deletes on a phone', async ({ page }, testInfo) => {
  const nickname = 'Test lifecycle sprout ' + randomUUID();
  const siteName = 'Test lifecycle room ' + randomUUID();
  const screenshot = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath(name), fullPage: true });
  };
  await logIn(page, 'synthetic-browser-owner');
  await page.goto('/sites/new');
  await page.getByLabel('Name', { exact: true }).fill(siteName);
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  await expect(page.getByRole('heading', { name: siteName, exact: true })).toBeVisible();
  await addPlantForSite(page.request, siteName, nickname);
  const plants = await (await page.request.get('/api/plants')).json();
  const plant = plants.find((item: { nickname: string }) => item.nickname === nickname);
  const path = '/plants/' + plant.id;
  expect((await page.request.post('/api/plants/' + plant.id + '/tasks/water/complete', { data: { request_id: randomUUID() } })).status()).toBe(200);
  await page.goto(path);
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await page.getByRole('button', { name: 'Move to graveyard', exact: true }).click();
  await expect(page.getByText(/In the graveyard since \d{4}-\d{2}-\d{2}/)).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Water', exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Care history', exact: true })).toContainText('Completed by');
  await screenshot('lifecycle-graveyard-plant.png');
  await page.getByRole('link', { name: 'Plants', exact: true }).click();
  await expect(page.getByRole('link', { name: nickname, exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Graveyard', exact: true }).click();
  await expect(page.getByRole('article').filter({ hasText: nickname })).toContainText('In the graveyard since');
  await screenshot('lifecycle-graveyard-list.png');
  await page.getByRole('link', { name: nickname, exact: true }).click();
  await page.getByRole('button', { name: 'Restore plant', exact: true }).click();
  await expect(page.getByText(/In the graveyard since/)).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Water', exact: true })).toBeVisible();
  await screenshot('lifecycle-restored.png');
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await page.getByRole('link', { name: 'Change species', exact: true }).click();
  await page.getByLabel('Species name', { exact: true }).fill('Testoria neblosa');
  await page.getByRole('button', { name: 'Search species', exact: true }).click();
  await page.getByRole('button', { name: 'Choose Testoria nebulosa', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save species', exact: true })).toHaveCount(0);
  await screenshot('lifecycle-species-confirm.png');
  await page.getByRole('button', { name: 'Confirm Testoria nebulosa', exact: true }).click();
  await page.getByRole('button', { name: 'Save species', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Species and site', exact: true })).toContainText('Testoria nebulosa Inventor');
  await expect(page.getByRole('region', { name: 'Care history', exact: true })).toContainText('Species changed from Testoria lucida Inventor to Testoria nebulosa Inventor');
  await expect(page.getByRole('region', { name: 'Care history', exact: true })).toContainText('Completed by');
  await screenshot('lifecycle-species-changed.png');
  // The same picker also accepts the merged name-index path, not only GBIF matches.
  await expect.poll(async () => (await (await page.request.get('/api/species/910001')).json()).names).toEqual(expect.arrayContaining([expect.objectContaining({ name: 'Δοκιμόφυτο', language: 'el' })]));
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await page.getByRole('link', { name: 'Change species', exact: true }).click();
  await page.getByLabel('Species name', { exact: true }).fill('Δοκιμόφυτο');
  await page.getByRole('button', { name: 'Search species', exact: true }).click();
  await expect(page.getByText('Matched Δοκιμόφυτο · Greek', { exact: true })).toBeVisible();
  await screenshot('lifecycle-common-name-search.png');
  await page.getByRole('button', { name: 'Choose Testoria lucida', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Confirm species', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Save species', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Species and site', exact: true })).toContainText('Testoria lucida Inventor');
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await page.getByRole('button', { name: 'Delete plant', exact: true }).click();
  const confirm = page.getByRole('button', { name: 'Permanently delete plant', exact: true });
  await expect(confirm).toBeDisabled();
  await page.getByLabel('Type the plant name to confirm', { exact: true }).fill('wrong');
  await expect(confirm).toBeDisabled();
  await page.getByLabel('Type the plant name to confirm', { exact: true }).fill(nickname);
  await screenshot('lifecycle-delete-confirm.png');
  await confirm.click();
  await expect(page).toHaveURL(/\/plants$/);
  await expect(page.getByRole('link', { name: nickname, exact: true })).toHaveCount(0);
  expect((await page.request.get('/api/plants/' + plant.id)).status()).toBe(404);
  await screenshot('lifecycle-deleted.png');
});
