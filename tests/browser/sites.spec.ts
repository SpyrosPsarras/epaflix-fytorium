import { expect, test } from '@playwright/test';
import { logIn } from './helpers/login';
import { randomUUID } from 'node:crypto';
import { insertPlantForSite } from './helpers/db';

test('creates, edits, lists and deletes a site on a phone', async ({ page }, testInfo) => {
  await logIn(page, 'synthetic-browser-owner');
  await page.getByRole('link', { name: 'Sites', exact: true }).click();
  await page.getByRole('link', { name: 'Create site', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Test browser room');
  await page.getByLabel('Location', { exact: true }).selectOption('indoor');
  await page.getByLabel('Light level', { exact: true }).selectOption('part_sun');
  await page.getByLabel('Grow light', { exact: true }).check();
  await page.getByLabel('Warm minimum °C', { exact: true }).fill('18');
  await page.getByLabel('Warm maximum °C', { exact: true }).fill('26');
  await page.getByLabel('Cold minimum °C', { exact: true }).fill('12');
  await page.getByLabel('Cold maximum °C', { exact: true }).fill('20');
  await page.getByLabel('Humidity', { exact: true }).selectOption('normal');
  if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath('sites-create.png'), fullPage: true });
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Test browser room', exact: true }) });
  await expect(card).toContainText('Indoor');
  await expect(card).toContainText('0 plants');
  await card.getByRole('link', { name: 'Edit', exact: true }).click();
  await expect(page.getByLabel('Warm minimum °C', { exact: true })).toHaveValue('18');
  await expect(page.getByLabel('Grow light', { exact: true })).toBeChecked();
  await page.getByLabel('Name', { exact: true }).fill('Test browser terrace');
  await page.getByLabel('Location', { exact: true }).selectOption('outdoor');
  await page.getByLabel('Light level', { exact: true }).selectOption('full_sun');
  await page.getByLabel('Grow light', { exact: true }).uncheck();
  await page.getByLabel('Warm minimum °C', { exact: true }).fill('28');
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Minimum must not exceed maximum.');
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Test browser terrace');
  await page.getByLabel('Warm minimum °C', { exact: true }).fill('');
  await page.getByLabel('Cold minimum °C', { exact: true }).fill('-5');
  await page.getByLabel('Humidity', { exact: true }).selectOption('dry');
  await page.getByLabel('Draft', { exact: true }).check();
  if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath('sites-edit.png'), fullPage: true });
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  const edited = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Test browser terrace', exact: true }) });
  await expect(edited).toContainText('Outdoor');
  await expect(edited).toContainText('0 plants');
  if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath('sites-list.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await edited.getByRole('link', { name: 'Edit', exact: true }).click();
  await expect(page.getByLabel('Light level', { exact: true })).toHaveValue('full_sun');
  await expect(page.getByLabel('Grow light', { exact: true })).not.toBeChecked();
  await expect(page.getByLabel('Warm minimum °C', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Cold minimum °C', { exact: true })).toHaveValue('-5');
  await expect(page.getByLabel('Humidity', { exact: true })).toHaveValue('dry');
  await expect(page.getByLabel('Draft', { exact: true })).toBeChecked();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Cancel', exact: true }).click();
  await edited.getByRole('button', { name: 'Delete', exact: true }).click();
  await edited.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(edited).toBeVisible();
  await edited.getByRole('button', { name: 'Delete', exact: true }).click();
  await edited.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(edited).toHaveCount(0);
});

test('counts a plant and refuses to delete its site on a phone', async ({ page }, testInfo) => {
  const suffix = randomUUID();
  const siteName = `Test occupied room ${suffix}`;
  await logIn(page, 'synthetic-browser-owner');
  await page.goto('/sites/new');
  await page.getByLabel('Name', { exact: true }).fill(siteName);
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: siteName, exact: true }) });
  await expect(card).toBeVisible();
  await insertPlantForSite(siteName, `Test plant ${suffix}`);
  await page.goto('/sites');
  await expect(card).toContainText('1 plant');
  await card.getByRole('button', { name: 'Delete', exact: true }).click();
  await card.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Move or remove the 1 plant on this site first.');
  await expect(card).toBeVisible();
  await expect(card).toContainText('1 plant');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath('sites-refused-delete.png'), fullPage: true });
});
