import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import sharp from 'sharp';
import { logIn } from './helpers/login';
import { addPlantForSite } from './helpers/plants';

test('adds a photo, picks its cover, browses updates and journal, and sets health on a phone', async ({ page }, testInfo) => {
  const suffix = randomUUID();
  const nickname = 'Test journal sprout ' + suffix;
  const siteName = 'Test photo site ' + suffix;
  const image = await sharp({ create: { width: 640, height: 480, channels: 3, background: '#508050' } }).jpeg().toBuffer();
  const screenshot = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath(name), fullPage: true });
  };
  const loadedImage = async (name: string) => {
    const img = page.getByRole('img', { name, exact: true });
    await expect(img).toBeVisible();
    await expect.poll(() => img.evaluate(element => element instanceof HTMLImageElement && element.complete && element.naturalWidth > 0)).toBe(true);
  };
  await logIn(page, 'synthetic-browser-owner');
  const site = await page.request.post('/api/sites', { data: { name: siteName, location: 'indoor', light: 'part_sun', humidity: 'normal', grow_light: false, draft: false } });
  expect(site.status()).toBe(201);
  await addPlantForSite(page.request, siteName, nickname);
  await page.goto('/plants');
  await page.getByLabel('Search plants', { exact: true }).fill(nickname);
  await page.getByRole('link', { name: nickname, exact: true }).click();
  await expect(page.getByRole('heading', { name: nickname, exact: true, level: 1 })).toBeVisible();
  const plantUrl = page.url();
  await expect(page.getByRole('img', { name: 'No plant photo yet', exact: true })).toBeVisible();
  const camera = page.getByLabel('Take photo', { exact: true });
  await expect(camera).toHaveAttribute('accept', 'image/*');
  await expect(camera).toHaveAttribute('capture', 'environment');
  await expect(camera).not.toHaveAttribute('multiple');
  const photoInput = page.getByLabel('Choose photos', { exact: true });
  await expect(photoInput).toHaveAttribute('accept', 'image/*');
  await expect(photoInput).not.toHaveAttribute('capture');
  await expect(photoInput).not.toHaveAttribute('multiple');
  await photoInput.setInputFiles({ name: 'synthetic.jpg', mimeType: 'image/jpeg', buffer: image });
  await page.getByLabel('Note', { exact: true }).fill('Test new leaf photo');
  await page.getByLabel('Photo health', { exact: true }).selectOption('good');
  await page.getByLabel('Taken on', { exact: true }).fill('2020-01-02');
  await screenshot('photos-upload.png');
  await page.getByRole('button', { name: 'Add photo update', exact: true }).click();
  await expect(page.getByText('Test new leaf photo', { exact: true })).toBeVisible();
  await expect(page.getByText('Health: good', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Use as cover', exact: true }).click();
  await loadedImage('Cover photo of ' + nickname);
  await expect(page.getByText('Cover photo', { exact: true })).toBeVisible();
  await expect(page.getByRole('article').locator('p').first()).toHaveText('2020-01-02 · Cover photo');
  await screenshot('photos-cover.png');
  await page.getByRole('link', { name: 'Plants', exact: true }).click();
  await page.getByLabel('Search plants', { exact: true }).fill(nickname);
  await loadedImage('Cover photo of ' + nickname);
  await screenshot('photos-list.png');
  await page.goto(plantUrl);
  await page.getByRole('link', { name: 'View all updates', exact: true }).click();
  await expect(page.getByRole('heading', { name: nickname + ' updates', exact: true })).toBeVisible();
  await expect(page.getByText('Test new leaf photo', { exact: true })).toBeVisible();
  await expect(page.getByRole('article').getByText('2020-01-02', { exact: true })).toBeVisible();
  await screenshot('photos-updates.png');
  await page.getByRole('link', { name: 'Journal', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Plant journal', exact: true })).toBeVisible();
  await expect(page.getByRole('article').filter({ hasText: nickname })).toContainText('Test new leaf photo');
  await screenshot('photos-journal.png');
  await page.goto(plantUrl + '/settings');
  await page.getByLabel('Health', { exact: true }).selectOption('very_good');
  await screenshot('photos-health.png');
  await page.getByRole('button', { name: 'Save plant', exact: true }).click();
  await expect(page.getByText('Health: very good', { exact: true })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete photo update', exact: true }).click();
  await expect(page.getByText('No photo updates yet.', { exact: true })).toBeVisible();
  await expect(page.getByRole('img', { name: 'No plant photo yet', exact: true })).toBeVisible();
});
