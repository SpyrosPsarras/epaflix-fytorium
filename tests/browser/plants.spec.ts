import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { logIn } from './helpers/login';

test('searches a typo, confirms, adds and edits a plant on a phone', async ({ page }, testInfo) => {
  const suffix = randomUUID();
  const siteName = 'Test plant room ' + suffix;
  const nickname = 'Test fuzzy sprout ' + suffix;
  const screenshot = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath(name), fullPage: true });
  };
  await logIn(page, 'synthetic-browser-owner');
  await page.goto('/sites/new');
  await page.getByLabel('Name', { exact: true }).fill(siteName);
  await page.getByRole('button', { name: 'Save site', exact: true }).click();
  await page.getByRole('link', { name: 'Home', exact: true }).click();
  await page.getByRole('link', { name: 'Plants', exact: true }).click();
  await page.getByRole('link', { name: 'Add plant', exact: true }).click();
  await page.getByLabel('Species name', { exact: true }).fill('Testoria neblosa');
  await page.getByRole('button', { name: 'Search species', exact: true }).click();
  await expect(page.getByText('Testoria alternativa Inventor', { exact: true })).toBeVisible();
  await screenshot('plants-candidates.png');
  await page.getByRole('button', { name: 'Choose Testoria nebulosa', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save plant', exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Confirm species', exact: true })).toBeVisible();
  await screenshot('plants-confirm.png');
  await page.getByRole('button', { name: 'Confirm Testoria nebulosa', exact: true }).click();
  await page.getByLabel('Nickname', { exact: true }).fill(nickname);
  await page.getByLabel('Cultivar', { exact: true }).fill('Test silver');
  await page.getByLabel('Birthday', { exact: true }).fill('2020-05-06');
  await page.getByLabel('Site', { exact: true }).selectOption({ label: siteName });
  await page.getByLabel('Pot type', { exact: true }).selectOption('terracotta');
  await page.getByLabel('Pot size in cm', { exact: true }).fill('18');
  await page.getByLabel('Drainage', { exact: true }).check();
  await page.getByLabel('Soil type', { exact: true }).selectOption('aroid');
  await page.getByLabel('Plant size', { exact: true }).selectOption('medium');
  await page.getByLabel('Growth stage', { exact: true }).selectOption('young');
  await page.getByLabel('Window distance in cm', { exact: true }).fill('70');
  await page.getByLabel('Grow light', { exact: true }).check();
  await page.getByLabel('Near AC', { exact: true }).check();
  await page.getByLabel('Near heater', { exact: true }).check();
  await page.getByLabel('Fertilizer type', { exact: true }).selectOption('sticks');
  await screenshot('plants-add.png');
  await page.getByRole('button', { name: 'Save plant', exact: true }).click();
  await expect(page.getByRole('heading', { name: nickname, exact: true })).toBeVisible();
  await expect(page.getByText('Testoria nebulosa Inventor', { exact: true })).toBeVisible();
  await expect(page.getByText('terracotta', { exact: true })).toBeVisible();
  await screenshot('plants-detail.png');
  const plantUrl = page.url();
  await page.getByRole('link', { name: 'Plants', exact: true }).click();
  await page.getByLabel('Search plants', { exact: true }).fill(nickname);
  const card = page.getByRole('article').filter({ hasText: nickname });
  await expect(card).toContainText(siteName);
  await expect(card.getByRole('img', { name: 'No plant photo yet' })).toBeVisible();
  await screenshot('plants-list.png');
  await page.getByLabel('Search plants', { exact: true }).fill('nebulosa');
  await expect(card).toBeVisible();
  await page.getByLabel('Search plants', { exact: true }).fill('no-such-name');
  await expect(card).toHaveCount(0);
  await page.goto(plantUrl);
  await page.getByRole('link', { name: siteName, exact: true }).click();
  await expect(page.getByRole('heading', { name: siteName, exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: nickname, exact: true })).toBeVisible();
  await screenshot('plants-site.png');
  await page.getByRole('link', { name: nickname, exact: true }).click();
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await expect(page.getByLabel('Pot size in cm', { exact: true })).toHaveValue('18');
  await page.getByLabel('Pot type', { exact: true }).selectOption('ceramic');
  await page.getByLabel('Window distance in cm', { exact: true }).fill('120');
  await page.getByLabel('Near heater', { exact: true }).uncheck();
  await screenshot('plants-settings.png');
  await page.getByRole('button', { name: 'Save plant', exact: true }).click();
  await expect(page.getByText('ceramic', { exact: true })).toBeVisible();
  await expect(page.getByText('120', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Plant settings', exact: true }).click();
  await expect(page.getByLabel('Pot type', { exact: true })).toHaveValue('ceramic');
  await expect(page.getByLabel('Near heater', { exact: true })).not.toBeChecked();
});
