import { expect, test } from '@playwright/test';
import { logIn } from './helpers/login';

test('imports Planta plants with fuzzy confirmation, cover photos and continued care dates on a phone', async ({ page }, testInfo) => {
  const screenshot = async (name: string) => {
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    if (process.env.PLAYWRIGHT_KEEP_ARTIFACTS === '1') await page.screenshot({ path: testInfo.outputPath(name), fullPage: true });
  };
  await logIn(page, 'synthetic-browser-owner');
  await page.request.post('/__test/clock', { data: { action: 'set', at: '2026-06-10T12:00:00Z' } });
  try {
    await page.getByRole('link', { name: 'Import from Planta', exact: true }).click();
    await page.getByLabel('One-time app code', { exact: true }).fill('synthetic-browser-import');
    await screenshot('planta-code.png');
    let releaseCredit!: () => void;
    const creditHeld = new Promise<void>(resolve => { releaseCredit = resolve; });
    await page.route('**/api/species/*/photo/credit', async route => {
      await creditHeld;
      await route.continue();
    });
    await page.getByRole('button', { name: 'Fetch Planta plants', exact: true }).click();
    const firstChoice = page.getByText('This is my plant', { exact: true }).first();
    await expect(firstChoice).toBeVisible();
    await firstChoice.scrollIntoViewIfNeeded();
    const beforeCredit = await firstChoice.boundingBox();
    expect(beforeCredit).not.toBeNull();
    releaseCredit();
    await expect(page.getByRole('link', { name: 'CC BY 4.0 · Photo: Synthetic photographer', exact: true }).first()).toBeVisible();
    await expect.poll(() => page.getByRole('img', { name: 'Reference photo of Testoria nebulosa', exact: true })
      .evaluate(element => element instanceof HTMLImageElement && element.complete && element.naturalWidth > 0)).toBe(true);
    expect(await firstChoice.boundingBox()).toEqual(beforeCredit);
    await page.unrouteAll({ behavior: 'wait' });
    const unmatched = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Test import unmatched', exact: true }) });
    await expect(unmatched.getByLabel('Species name', { exact: true })).toBeVisible();
    await expect(unmatched.getByRole('button', { name: 'Skip plant', exact: true })).toHaveCount(1);
    const searchToggle = unmatched.getByRole('button', { name: 'Search for a species', exact: true });
    await expect(searchToggle).toHaveAttribute('aria-expanded', 'true');
    await searchToggle.click();
    await expect(unmatched.getByLabel('Species name', { exact: true })).toHaveCount(0);
    await unmatched.getByRole('button', { name: 'Skip plant', exact: true }).click();
    const fuzzy = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Test import amber', exact: true }) });
    await expect(page.getByText('Plants marked Needs review need one tap: choose the matching species or skip. Everything else is ready.', { exact: true })).toBeVisible();
    await expect(fuzzy).toContainText('Needs review');
    await expect(fuzzy).toContainText('Which picture looks like your plant?');
    await expect(fuzzy.getByRole('button', { name: 'Skip plant', exact: true })).toBeVisible();
    await expect(fuzzy.getByText('Looks most like your photo', { exact: true })).toBeVisible();
    await expect(fuzzy.getByRole('button', { name: 'Not sure: import as Testoria (any kind)', exact: true })).toBeVisible();
    await expect(fuzzy.getByText('Synthetic cloudleaf', { exact: true })).toBeVisible();
    await expect(page.getByText(/%|confidence/i)).toHaveCount(0);
    const ready = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Test import blue', exact: true }) });
    await expect(ready).toContainText('✓ Ready to import');
    await expect(ready.getByRole('button', { name: 'Change species or skip', exact: true })).toBeVisible();
    await expect(ready.getByRole('button', { name: 'Skip plant', exact: true })).toHaveCount(0);
    await expect(page.getByRole('article').first()).toContainText('Test import amber');
    const summary = page.getByRole('status').filter({ hasText: '1 plant still needs review:' });
    await expect(summary).toHaveCount(2);
    await summary.first().getByRole('link', { name: 'Test import amber', exact: true }).click();
    const plantaPhoto = fuzzy.getByRole('img', { name: 'Planta photo of Test import amber', exact: true });
    await expect(plantaPhoto).toBeVisible();
    await expect.poll(() => plantaPhoto.evaluate(element => element instanceof HTMLImageElement && element.naturalWidth > 0)).toBe(true);
    const reference = fuzzy.getByRole('img', { name: 'Reference photo of Testoria nebulosa', exact: true });
    await expect(reference).toBeVisible();
    await expect.poll(() => reference.evaluate(element => element instanceof HTMLImageElement && element.naturalWidth > 0)).toBe(true);
    await expect(fuzzy.getByRole('link', { name: 'CC BY 4.0 · Photo: Synthetic photographer', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Import confirmed plants', exact: true })).toBeDisabled();
    await screenshot('planta-review.png');
    await expect(fuzzy.getByRole('button', { name: 'This is Testoria nebulosa', exact: true })).toBeVisible();
    await expect(fuzzy.getByText('This is my plant', { exact: true }).first()).toBeVisible();
    await fuzzy.getByRole('button', { name: 'Search for another species', exact: true }).click();
    await expect(fuzzy.getByRole('button', { name: 'Skip plant', exact: true })).toHaveCount(1);
    await fuzzy.getByLabel('Species name', { exact: true }).fill('Testoria neblosa');
    await fuzzy.getByRole('button', { name: 'Search species', exact: true }).click();
    const searched = fuzzy.getByRole('article').filter({ hasText: 'Testoria nebulosa Inventor' });
    await expect(searched.getByRole('img', { name: 'Reference photo of Testoria nebulosa', exact: true })).toBeVisible();
    await expect(fuzzy.getByText(/%|confidence/i)).toHaveCount(0);
    await fuzzy.getByRole('button', { name: 'Skip plant', exact: true }).click();
    await expect(fuzzy).toContainText('Skipped. This plant will not be imported.');
    await expect(fuzzy.getByRole('button', { name: 'Skip plant', exact: true })).toHaveCount(0);
    await fuzzy.getByRole('button', { name: 'Undo skip', exact: true }).click();
    await expect(fuzzy).toContainText('Undo skip:');
    let releaseReview!: () => void;
    const reviewHeld = new Promise<void>(resolve => { releaseReview = resolve; });
    await page.route('**/api/import/planta/*', async route => {
      if (route.request().method() === 'PUT') await reviewHeld;
      await route.continue();
    });
    await fuzzy.getByRole('button', { name: 'This is Testoria nebulosa', exact: true }).click();
    try {
      await expect(fuzzy.getByRole('button', { name: 'This is Testoria nebulosa', exact: true })).toBeDisabled();
      await expect(fuzzy.getByText('This is my plant', { exact: true }).first()).toHaveCSS('opacity', '0.5');
    } finally { releaseReview(); }
    await page.unrouteAll({ behavior: 'wait' });
    await expect(fuzzy).toContainText('✓ Ready to import');
    await expect(fuzzy).toContainText('Testoria nebulosa');
    await expect(fuzzy.getByRole('button', { name: 'Skip plant', exact: true })).toHaveCount(0);
    await expect(summary).toHaveCount(0);
    await page.getByRole('button', { name: 'Import confirmed plants', exact: true }).click();
    await expect(page.getByText('Import complete.', { exact: true })).toBeVisible();
    await screenshot('planta-committed.png');
    await page.getByRole('link', { name: 'View imported plants', exact: true }).click();
    await page.getByLabel('Search plants', { exact: true }).fill('Test import amber');
    const cover = page.getByRole('img', { name: 'Cover photo of Test import amber', exact: true });
    await expect(cover).toBeVisible();
    await expect.poll(() => cover.evaluate(element => element instanceof HTMLImageElement && element.complete && element.naturalWidth > 0)).toBe(true);
    await screenshot('planta-collection.png');
    await page.getByRole('link', { name: 'Test import amber', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Test import amber', exact: true, level: 1 })).toBeVisible();
    await expect(page.getByRole('region', { name: 'Water', exact: true })).toContainText('2026-06-08');
    await page.getByRole('region', { name: 'Based on', exact: true }).getByText('Water', { exact: true }).click();
    await expect(page.getByRole('region', { name: 'Based on', exact: true })).toContainText('counted from last completion on 2026-06-01');
    await screenshot('planta-next-due.png');
    await page.goto('/plants');
    await page.getByLabel('Search plants', { exact: true }).fill('Test import blue');
    await expect(page.getByRole('link', { name: 'Test import blue', exact: true })).toBeVisible();
  } finally { await page.request.post('/__test/clock', { data: { action: 'reset' } }); }
});
